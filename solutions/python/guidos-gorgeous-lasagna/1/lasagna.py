EXPECTED_BAKE_TIME = 40
def bake_time_remaining(elapsed_bake_time):
    EXPECTED_BAKE_TIME - elapsed_bake_time
    return EXPECTED_BAKE_TIME - elapsed_bake_time
def preparation_time_in_minutes(number_of_layers):
    number_of_layers * 2
    return number_of_layers * 2
def elapsed_time_in_minutes(elapsed_bake_time, number_of_layers):
    bake_time_remaining(elapsed_bake_time)
    preparation_time_in_minutes(number_of_layers)
    return bake_time_remaining(elapsed_bake_time) + preparation_time_in_minutes(number_of_layers)
    


